export function calculateWIP(order: ProductionOrder): StageWIPMetrics {
  const cuttingWip = Math.max(0, order.orderQty - order.cutQty);
  const sewingWip = Math.max(0, order.cutQty - order.sewingQty);
  const finishingWip = Math.max(0, order.sewingQty - order.finishingQty);
  const packingWip = Math.max(0, order.finishingQty - order.packedQty);
  const readyToShipWip = Math.max(0, order.packedQty - order.shippedQty);
  const totalBalanceToShip = Math.max(0, order.orderQty - order.shippedQty);
  const stageCompletionPct = order.orderQty > 0 ? (order.shippedQty / order.orderQty) * 100 : 0;

  return {
    cuttingWip,
    sewingWip,
    finishingWip,
    packingWip,
    readyToShipWip,
    totalBalanceToShip,
    stageCompletionPct
  };
}
